import assert from 'node:assert/strict';
import {parseBits} from '../site/binary.mjs';
import {programFragment,parseProgramFragment} from '../site/program-link.mjs';

export async function checkProgramLinks(page) {
  const base=new URL(page.url());base.hash='';base.search='';
  const source='10111000 00101010 00000000 11110100 # private comment omitted',expected=Uint8Array.from([0xB8,42,0,0xF4]);
  await page.locator('#binary-editor').fill(source);await page.locator('#load-program').click();
  await page.locator('#binary-editor').fill('11110100 # unloaded draft');
  const link=await page.locator('#program-link').inputValue();
  assert.deepEqual(parseProgramFragment(new URL(link).hash),expected,'sharing uses loaded bytes, not a draft');
  assert.equal(new URL(link).search,'');assert.equal(link.includes('private'),false);
  assert.equal(await page.locator('#open-program-link').getAttribute('href'),link);
  const requests=[];const collect=request=>requests.push(request.url());page.on('request',collect);
  await page.goto(link);await page.reload();page.off('request',collect);
  await page.waitForFunction(()=>document.getElementById('lesson').textContent.startsWith('Shared literal'));
  assert.deepEqual(parseBits(await page.locator('#binary-editor').inputValue()),expected);
  assert.equal(await page.locator('#step-count').textContent(),'0000');
  assert.equal(await page.locator('[data-register="AX"] .register-value').textContent(),'0000','opening a program link does not execute it');
  assert.ok(requests.length>0&&requests.every(url=>!url.includes('program=v1.')),'program fragments are absent from actual reload network requests');
  await page.locator('#step').click();assert.equal(await page.locator('[data-register="AX"] .register-value').textContent(),'002A');
  const snapshot=()=>page.locator('#registers,#memory,#history-position,#step-count,#run-state').allTextContents();
  const before=await snapshot();
  await page.evaluate(()=>{window.location.hash='program=v2.F4';});
  await page.waitForFunction(()=>document.getElementById('editor-status').textContent.includes('Invalid program link'));
  assert.deepEqual(await snapshot(),before,'malformed hash navigation preserves recorded state');
  assert.deepEqual(parseBits(await page.locator('#binary-editor').inputValue()),expected);
  await page.evaluate(()=>history.back());
  await page.waitForFunction(()=>document.getElementById('step-count').textContent==='0000');
  assert.deepEqual(parseBits(await page.locator('#binary-editor').inputValue()),expected);
  await page.evaluate(()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw new Error('denied');}}});});
  await page.locator('#copy-program-link').click();
  await page.waitForFunction(()=>document.getElementById('share-status').textContent.includes('Clipboard unavailable'));
  assert.equal(await page.evaluate(()=>document.activeElement.id),'program-link');
  assert.equal(await page.locator('#program-link').evaluate(input=>input.selectionEnd-input.selectionStart),link.length,'fallback selects the full copyable link');
  await page.evaluate(()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.copiedProgramLink=text;}}});});
  await page.locator('#copy-program-link').click();
  await page.waitForFunction(()=>document.getElementById('share-status').textContent.includes('Program link copied'));
  assert.equal(await page.evaluate(()=>window.copiedProgramLink),link,'copy sends the exact loaded-byte URL to the clipboard API');
  const maximum=new Uint8Array(512);maximum[0]=0xF4;
  const boundary=new URL(base);boundary.hash=programFragment(maximum);await page.goto(boundary.href);
  await page.waitForFunction(()=>document.getElementById('byte-count').textContent==='512 BYTES');
  assert.equal(await page.locator('#step-count').textContent(),'0000');
  assert.deepEqual(parseBits(await page.locator('#binary-editor').inputValue()),maximum);
  const malformed=new URL(base);malformed.hash='program=v1.'+'00'.repeat(513);await page.goto(malformed.href);await page.reload();
  await page.waitForFunction(()=>document.getElementById('editor-status').textContent.includes('Invalid program link'));
  assert.equal(await page.locator('#preset').inputValue(),'immediates','invalid startup link retains the default program');
  assert.equal(await page.locator('#step-count').textContent(),'0000');
  await page.locator('#binary-editor').fill('10110000 11110100 10100010 00000101 01111100 10010000');
  await page.locator('#load-program').click();const original=await page.locator('#program-link').inputValue();
  for(let step=0;step<3;step++)await page.locator('#step').click();
  assert.equal(await page.locator('#run-state').textContent(),'HALTED');
  assert.equal(await page.locator('#program-link').inputValue(),original,'self-modification does not silently change the shared loaded program');
  await page.evaluate(()=>{
    window.originalArrayBuffer=File.prototype.arrayBuffer;
    File.prototype.arrayBuffer=function(){return window.originalArrayBuffer.call(this).then(bytes=>new Promise(resolve=>{window.finishOldImport=()=>resolve(bytes);}));};
  });
  await page.locator('#import-program').setInputFiles({name:'older.bin',mimeType:'application/octet-stream',buffer:Buffer.from([0xF4])});
  await page.waitForFunction(()=>typeof window.finishOldImport==='function');
  await page.evaluate(()=>{window.location.hash='program=v1.B82A00F4';});
  await page.waitForFunction(()=>document.getElementById('byte-count').textContent==='4 BYTES');
  await page.evaluate(()=>{File.prototype.arrayBuffer=window.originalArrayBuffer;window.finishOldImport();});
  await page.waitForFunction(()=>document.getElementById('import-program').value==='');
  assert.deepEqual(parseBits(await page.locator('#binary-editor').inputValue()),expected,'a newer shared link cancels a delayed older file import');
  await page.setViewportSize({width:320,height:900});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'shared-link controls fit 320px');
  await page.goto(base.href);
  await page.waitForFunction(()=>document.getElementById('byte-count').textContent.includes('BYTES'));
}
