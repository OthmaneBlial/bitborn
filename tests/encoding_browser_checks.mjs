import assert from 'node:assert/strict';
import {checkBitKeyboard} from './bit_keyboard_browser_checks.mjs';

export async function checkEncoding(page) {
  const initial=await page.locator('#play-registers').textContent();
  for(const width of [1440,320]) {
    await page.setViewportSize({width,height:1000});
    await page.locator('#instruction-select').selectOption('mov32');
    await page.locator('#decode-mode').selectOption('16');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV AX, 42');
    assert.match(await page.locator('#encoding-explanation').textContent(),/consumes 3 of the 5/);
    assert.equal(await page.locator('#execute-instruction').isEnabled(),true);
    await page.locator('#decode-mode').selectOption('32');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV EAX, 42');
    assert.equal(await page.locator('#execute-instruction').isDisabled(),true);
    await page.locator('#decode-mode').selectOption('64');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV EAX, 42');
    assert.match(await page.locator('#encoding-explanation').textContent(),/clears its upper 32 bits/);
    await page.locator('#instruction-select').selectOption('mov64');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV R8, 18446744073709551615');
    assert.equal(await page.locator('#execute-instruction').isDisabled(),true);
    assert.match(await page.locator('[data-bit="0-0"]').getAttribute('aria-label'),/B: register extension/);
    await page.locator('[data-bit="0-0"]').press('Space');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV RAX, 18446744073709551615');
    assert.equal(await page.evaluate(()=>document.activeElement.dataset.bit),'0-0');
    await page.locator('[data-bit="0-3"]').click();
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV EAX, 4294967295');
    assert.match(await page.locator('#encoding-explanation').textContent(),/consumes 6 of the 10/);
    assert.equal(await page.locator('#play-registers').textContent(),initial,'read-only inspection never changes simulated state');
    await page.locator('#instruction-select').selectOption('movRegister');
    await page.locator('#decode-mode').selectOption('16');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV AX, BX');
    assert.equal(await page.locator('#execute-instruction').isEnabled(),true,'unprefixed 16-bit register forms are modeled');
    assert.match(await page.locator('[data-bit="0-1"]').getAttribute('aria-label'),/Direction/);
    assert.match(await page.locator('[data-bit="1-0"]').getAttribute('aria-label'),/Destination register/);
    await page.locator('[data-bit="0-1"]').press('Space');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV BX, AX');
    assert.match(await page.locator('[data-bit="1-0"]').getAttribute('aria-label'),/Source register/);
    await page.locator('#decode-mode').selectOption('32');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV EBX, EAX');
    await page.locator('#instruction-select').selectOption('movRegister64');await page.locator('#decode-mode').selectOption('64');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV R8, RBX');
    await page.locator('[data-bit="0-2"]').click();
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV R8, R11');
    await page.locator('#instruction-select').selectOption('movByte');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV AL, AH');
    await page.locator('#instruction-select').selectOption('movByteRex');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV AL, SPL');
    await page.locator('[data-bit="0-3"]').click();
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV AL, SPL','REX.W does not widen byte MOV');
    assert.match(await page.locator('[data-bit="0-3"]').getAttribute('aria-label'),/unused by byte MOV/);
    assert.equal(await page.locator('#play-registers').textContent(),initial);
    await page.locator('#instruction-select').selectOption('movMemoryBP');await page.locator('#decode-mode').selectOption('16');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV AX, [BP-2]');
    assert.match(await page.locator('#encoding-explanation').textContent(),/Default SS because BP/);
    assert.equal(await page.locator('#execute-instruction').isEnabled(),true,'unprefixed 16-bit memory MOV is modeled');
    assert.match(await page.locator('[data-bit="2-7"]').getAttribute('aria-label'),/Displacement sign bit/);
    await page.locator('[data-bit="2-7"]').click();
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV AX, [BP+126]');
    await page.locator('#instruction-select').selectOption('movMemoryAbsolute');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV DX, [32]');
    assert.match(await page.locator('#encoding-explanation').textContent(),/Default DS; no BP/);
    await page.locator('#instruction-select').selectOption('movMemoryPair');
    assert.equal(await page.locator('#decoded-instruction').textContent(),'MOV CX, [BX+SI]');
    assert.match(await page.locator('[data-bit="1-0"]').getAttribute('aria-label'),/Memory-address selector/);
    await page.locator('#decode-mode').selectOption('32');
    assert.match(await page.locator('#encoding-explanation').textContent(),/16-bit addressing context only/);
    assert.equal(await page.locator('#execute-instruction').isDisabled(),true);
    assert.equal(await page.locator('#play-registers').textContent(),initial,'memory-address inspection reads no model RAM or registers');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`wide instruction inspection fits ${width}px`);
  }
  await page.locator('#instruction-select').selectOption('mov64');await page.locator('#decode-mode').selectOption('16');await page.locator('#reset-bits').click();
  assert.equal(await page.locator('#decoded-instruction').textContent(),'DEC CX');
  await page.locator('#instruction-select').selectOption('mov');
  await page.locator('#execute-instruction').click();
  await page.locator('#instruction-select').selectOption('movRegister');await page.locator('[data-bit="0-1"]').click();
  const flags=await page.locator('#play-registers .register').filter({hasText:/^(ZF|CF)/}).allTextContents();
  await page.locator('#execute-instruction').click();
  assert.equal(await page.locator('#play-registers .register').filter({hasText:/^BX/}).locator('strong').textContent(),'002A');
  assert.deepEqual(await page.locator('#play-registers .register').filter({hasText:/^(ZF|CF)/}).allTextContents(),flags);
  await page.locator('#instruction-select').selectOption('movByte');
  assert.equal(await page.locator('#execute-instruction').isEnabled(),true);
  await page.locator('#execute-instruction').click();
  assert.equal(await page.locator('#play-registers .register').filter({hasText:/^AX/}).locator('strong').textContent(),'0000','AH copied into AL while preserving AH');
  await page.locator('#reset-state').click();await page.locator('#instruction-select').selectOption('mov');
  const beforeBranches=await page.locator('#play-registers').textContent();
  for(const mode of ['16','32','64']) {
    await page.locator('#instruction-select').selectOption('shortBranch');await page.locator('#decode-mode').selectOption(mode);
    assert.equal(await page.locator('#decoded-instruction').textContent(),'JL -2');
    assert.match(await page.locator('#encoding-explanation').textContent(),/SF != OF/);
    assert.match(await page.locator('[data-bit="0-0"]').getAttribute('aria-label'),/Condition inversion/);
    assert.match(await page.locator('[data-bit="0-2"]').getAttribute('aria-label'),/Condition group selector/);
    assert.match(await page.locator('[data-bit="1-7"]').getAttribute('aria-label'),/Signed rel8 sign/);
    assert.equal(await page.locator('#execute-instruction').isEnabled(),mode==='16');
    await page.locator('[data-bit="0-0"]').click();assert.equal(await page.locator('#decoded-instruction').textContent(),'JGE -2');
    assert.match(await page.locator('#encoding-explanation').textContent(),/SF = OF/);
    await page.locator('[data-bit="1-7"]').click();assert.equal(await page.locator('#decoded-instruction').textContent(),'JGE +126');
    assert.equal(await page.locator('#play-registers').textContent(),beforeBranches,'inspection of branch bits does not read/change runtime flags or registers');
  }
  await page.locator('#decode-mode').selectOption('16');await page.locator('#instruction-select').selectOption('mov');
  await checkBitKeyboard(page);
}
